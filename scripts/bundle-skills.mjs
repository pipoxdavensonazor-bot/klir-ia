function parseFrontmatter(content) {
  const match = content.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match) return { name: "", description: "", body: content };
  const fm = match[1];
  const body = match[2];
  const name = fm.match(/^name:\s*(.+)$/m)?.[1]?.trim() ?? "";
  const descMatch = fm.match(/^description:\s*"?([\s\S]*?)"?\s*(?:\nmetadata:|$)/m);
  const description = descMatch?.[1]?.trim().replace(/^"|"$/g, "") ?? "";
  return { name, description, body };
}

function main() {
  const identity = fs.readFileSync(path.join(ROOT, "catalog", "identity.md"), "utf8");
  const productMarketing = fs.readFileSync(path.join(ROOT, "catalog", "product-marketing.md"), "utf8");
  const tradingToolkitPath = path.join(ROOT, "catalog", "trading-toolkit.md");
  const tradingToolkit = fs.existsSync(tradingToolkitPath)
    ? fs.readFileSync(tradingToolkitPath, "utf8")
    : "";

  const skills = {};
  for (const dir of fs.readdirSync(SKILLS_DIR, { withFileTypes: true }).filter((d) => d.isDirectory())) {
    const skillPath = path.join(SKILLS_DIR, dir.name, "SKILL.md");
    if (!fs.existsSync(skillPath)) continue;
    const raw = fs.readFileSync(skillPath, "utf8");
    const { name, description, body } = parseFrontmatter(raw);
    skills[dir.name] = {
      name: name || dir.name,
      description,
      body,
      category: CATEGORY_MAP[dir.name] ?? "Marketing",
    };
  }

  const out = `// AUTO-GENERATED by scripts/bundle-skills.mjs — do not edit
export const IDENTITY = ${JSON.stringify(identity)};
export const PRODUCT_MARKETING = ${JSON.stringify(productMarketing)};
export const TRADING_TOOLKIT = ${JSON.stringify(tradingToolkit)};
export const SKILLS_DATA: Record<string, { name: string; description: string; body: string; category: string }> = ${JSON.stringify(skills, null, 2)};
`;

  fs.writeFileSync(OUT, out, "utf8");
  console.log(`Bundled ${Object.keys(skills).length} skills → src/lib/ai/skills-data.ts`);
}

main();
